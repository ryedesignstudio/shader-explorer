import * as THREE from 'three';
import { VERTEX_SHADER, type Preset } from '../types';

export function hexToVec3(hex: string): THREE.Vector3 {
  const clean = hex.replace('#', '');
  const r = parseInt(clean.substring(0, 2), 16) / 255;
  const g = parseInt(clean.substring(2, 4), 16) / 255;
  const b = parseInt(clean.substring(4, 6), 16) / 255;
  return new THREE.Vector3(r, g, b);
}

export function vec3ToHex(vec: THREE.Vector3): string {
  const r = Math.round(vec.x * 255).toString(16).padStart(2, '0');
  const g = Math.round(vec.y * 255).toString(16).padStart(2, '0');
  const b = Math.round(vec.z * 255).toString(16).padStart(2, '0');
  return `#${r}${g}${b}`;
}

export function createMaterial(
  preset: Preset,
  colors: Record<string, string>
): THREE.ShaderMaterial {
  const uniforms: Record<string, { value: THREE.Vector3 | THREE.Vector2 | number }> = {
    u_time: { value: 0 },
    u_mouse: { value: new THREE.Vector2(0.5, 0.5) },
    u_resolution: { value: new THREE.Vector2(800, 600) },
  };

  // Add color uniforms
  for (const colorDef of preset.colors) {
    const hexValue = colors[colorDef.key] || colorDef.defaultValue;
    uniforms[`u_${colorDef.key}`] = { value: hexToVec3(hexValue) };
  }

  return new THREE.ShaderMaterial({
    vertexShader: VERTEX_SHADER,
    fragmentShader: preset.fragmentShader,
    uniforms,
  });
}

export function updateColors(
  material: THREE.ShaderMaterial,
  preset: Preset,
  colors: Record<string, string>
): void {
  for (const colorDef of preset.colors) {
    const hexValue = colors[colorDef.key] || colorDef.defaultValue;
    const uniformName = `u_${colorDef.key}`;
    if (material.uniforms[uniformName]) {
      (material.uniforms[uniformName].value as THREE.Vector3).copy(hexToVec3(hexValue));
    }
  }
}

export function generateExportCode(preset: Preset, colors: Record<string, string>): string {
  const colorUniforms = preset.colors
    .map((c) => {
      const hex = colors[c.key] || c.defaultValue;
      const vec = hexToVec3(hex);
      return `    u_${c.key}: { value: new THREE.Vector3(${vec.x.toFixed(3)}, ${vec.y.toFixed(3)}, ${vec.z.toFixed(3)}) },`;
    })
    .join('\n');

  return `// ${preset.name} - Generated by Shader Explorer
import * as THREE from 'three';

const vertexShader = \`
  varying vec2 v_uv;
  void main() {
    v_uv = uv;
    gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
  }
\`;

const fragmentShader = \`
${preset.fragmentShader}
\`;

// Setup
const scene = new THREE.Scene();
const camera = new THREE.OrthographicCamera(-1, 1, 1, -1, 0, 1);
const renderer = new THREE.WebGLRenderer();
renderer.setSize(window.innerWidth, window.innerHeight);
document.body.appendChild(renderer.domElement);

const uniforms = {
    u_time: { value: 0 },
    u_mouse: { value: new THREE.Vector2(0.5, 0.5) },
    u_resolution: { value: new THREE.Vector2(window.innerWidth, window.innerHeight) },
${colorUniforms}
};

const material = new THREE.ShaderMaterial({ vertexShader, fragmentShader, uniforms });
const geometry = new THREE.PlaneGeometry(2, 2);
const mesh = new THREE.Mesh(geometry, material);
scene.add(mesh);

// Mouse tracking
document.addEventListener('mousemove', (e) => {
    uniforms.u_mouse.value.set(e.clientX / window.innerWidth, 1 - e.clientY / window.innerHeight);
});

// Resize handling
window.addEventListener('resize', () => {
    renderer.setSize(window.innerWidth, window.innerHeight);
    uniforms.u_resolution.value.set(window.innerWidth, window.innerHeight);
});

// Animation loop
function animate() {
    uniforms.u_time.value = performance.now() / 1000;
    renderer.render(scene, camera);
    requestAnimationFrame(animate);
}
animate();
`;
}
